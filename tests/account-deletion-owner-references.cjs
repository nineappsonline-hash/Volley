const {PGlite}=require('@electric-sql/pglite');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const db=new PGlite();
 const admin='00000000-0000-0000-0000-000000000001';
 const owner='00000000-0000-0000-0000-000000000002';
 const other='00000000-0000-0000-0000-000000000003';
 await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
 CREATE FUNCTION public.is_super_admin() RETURNS boolean LANGUAGE sql AS $$ SELECT auth.uid()='${admin}'::uuid $$;
 CREATE TABLE auth.users(id uuid PRIMARY KEY,email text);
 CREATE TABLE public.profiles(id uuid PRIMARY KEY,email text,name text);
 CREATE TABLE public.venues(id int PRIMARY KEY,owner_profile_id uuid REFERENCES profiles(id));
 CREATE TABLE public.playground_owners(id int PRIMARY KEY,profile_id uuid REFERENCES profiles(id) ON DELETE CASCADE,approved_by uuid REFERENCES profiles(id));
 CREATE TABLE preserved_bookings(id int PRIMARY KEY,venue_id int REFERENCES venues(id),amount numeric);
 INSERT INTO auth.users VALUES ('${admin}','admin@example.test'),('${owner}','owner@example.test'),('${other}','other@example.test');
 INSERT INTO profiles SELECT id,email,'Test' FROM auth.users;
 INSERT INTO venues VALUES (1,'${owner}'),(2,'${other}');
 INSERT INTO playground_owners VALUES (1,'${owner}',NULL),(2,'${other}','${owner}');
 INSERT INTO preserved_bookings VALUES (1,1,100);
 SET test.uid='${admin}';`);
 await db.exec(fs.readFileSync('supabase/migrations/20261120000000_atomic_account_deletion.sql','utf8'));
 const remove=(id=owner,confirmation='owner@example.test')=>db.query('SELECT platform_delete_account($1,$2)',[id,confirmation]);
 await assert.rejects(remove(),e=>e.code==='23503','reproduces the restrictive owner-reference error');
 assert.equal((await db.query('SELECT count(*)::int n FROM auth.users')).rows[0].n,3,'failed deletion is atomic');
 await db.exec(fs.readFileSync('supabase/migrations/20270108000003_account_deletion_owner_references.sql','utf8'));
 await assert.rejects(remove(owner,'wrong@example.test'));
 await assert.rejects(remove(admin,'admin@example.test'));
 await db.exec(`SET test.uid='${other}'`);await assert.rejects(remove(),e=>e.code==='42501');
 await db.exec(`SET test.uid=''`);await assert.rejects(remove(),e=>e.code==='42501');
 await db.exec(`SET test.uid='${admin}'`);
 await remove();
 assert.equal((await db.query('SELECT count(*)::int n FROM auth.users')).rows[0].n,2);
 assert.equal((await db.query('SELECT count(*)::int n FROM profiles')).rows[0].n,2);
 assert.deepEqual((await db.query('SELECT * FROM venues ORDER BY id')).rows,[{id:1,owner_profile_id:null},{id:2,owner_profile_id:other}]);
 assert.deepEqual((await db.query('SELECT * FROM playground_owners')).rows,[{id:2,profile_id:other,approved_by:null}]);
 assert.deepEqual((await db.query('SELECT * FROM preserved_bookings')).rows,[{id:1,venue_id:1,amount:'100'}]);
 assert.equal((await db.query(`SELECT has_function_privilege('anon','public.platform_delete_account(uuid,text)','execute') allowed`)).rows[0].allowed,false);
 await db.close();
 console.log('PASS: reproduces account-deletion failure; fix preserves courts, bookings, amounts and other owners; auth/profile removal stays atomic, authorized and confirmed');
})().catch(e=>{console.error(e);process.exit(1)});
