const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
const output = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib/game-filters.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const api = {};
new Function('exports', output)(api);
const { gameLocations, matchesGameLocation: matches } = api;
const game = { area: ' Heliopolis ', playground: { area: 'Nasr City', governorate: 'Cairo' } };
assert.deepEqual(gameLocations(game), ['Nasr City', 'Cairo', 'Heliopolis']);
for (const location of gameLocations(game)) assert.ok(matches(game, location));
assert.ok(matches(game, ' cairo '));
assert.ok(matches({ area: 'مدينة نصر' }, 'مدينة نصر'));
assert.ok(matches({ area: 'Cairo' }, 'all'));
assert.ok(!matches(game, 'Alexandria'));
assert.ok(!matches({}, 'Cairo'));
assert.ok(!matches({ area: '  ', playground: { area: '', governorate: null } }, 'Cairo'));
assert.ok(!matches({ area: 'Nasr City' }, '6th October City'));
console.log('PASS: governorate, venue area, legacy area, Arabic, whitespace, missing locations, and unrelated areas');
