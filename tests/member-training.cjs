const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const output = ts.transpileModule(fs.readFileSync('src/lib/member-training.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const helpers = {};
new Function('exports', output)(helpers);
const { nextTraining, futureSlots, profileAge, eligibleProgram, cairoNow } = helpers;
const now = '2026-10-11T12:00:00';
const member = { id: 'member', academy_id: 'academy', birth_date: '2000-10-12', gender: 'female' };
const weekly = { academy_id: 'academy', is_active: true, weekday: 0, time: '10:00:00', start_date: '2026-10-01', end_date: '2026-11-01', name: 'Weekly' };
assert.equal(nextTraining(member, [], [], [weekly], now).date, '2026-10-18');
assert.equal(nextTraining(member, [], [], [{ ...weekly, end_date: '2026-10-11' }], now), undefined);
const canceled = { academy_id: 'academy', date: '2026-10-18', time: '10:00:00', status: 'canceled' };
assert.equal(nextTraining(member, [], [canceled], [weekly], now).date, '2026-10-25', 'skip the canceled instance and show the next weekly session');
const slot = { session_date: '2026-10-12', starts_at: '09:00:00', seats_left: 0 };
const booking = { member_id: 'member', status: 'approved', details: { program: 'Booked group', sessions: [slot] } };
assert.equal(nextTraining(member, [booking], [], [weekly], now).name, 'Booked group');
assert.equal(nextTraining(member, [{ ...booking, status: 'rejected' }], [], [], now), undefined);
assert.equal(nextTraining({ ...member, id: 'other' }, [booking], [], [], now), undefined);
assert.equal(nextTraining(member, [], [], [], now, [{ active: true, gender: 'mixed', academy_id: 'academy', name: 'Academy group', slots: [slot] }]).name, 'Academy group');
assert.equal(futureSlots([{ ...slot, session_date: '2026-10-11', starts_at: '11:00:00' }, slot], now).length, 1);
assert.equal(profileAge(member.birth_date, '2026-10-11'), 25);
assert.equal(profileAge(member.birth_date, '2026-10-12'), 26);
assert.equal(eligibleProgram({ active: true, gender: 'male' }, member), false);
assert.equal(eligibleProgram({ active: true, gender: 'mixed', min_age: 18 }, { ...member, birth_date: null }), false);
assert.equal(cairoNow(new Date('2026-01-01T00:00:00Z')), '2026-01-01T02:00:00');
console.log('PASS: upcoming bookings, weekly schedules, cancellation, future slots, eligibility, age and Cairo time');

const { trainingPaymentHistory, bookingBalance, trainingAgenda } = helpers;
const paid = { ...booking, id: 'admin-assigned', amount: 800, expires_on: '2026-11-01', registered_on: '2026-10-10', reviewed_at: '2026-10-10T22:30:00Z' };
const pending = { ...paid, id: 'pending', status: 'awaiting_payment', amount: 400 };
const history = trainingPaymentHistory('member', [], [paid, pending, { ...paid, member_id: 'other' }]);
assert.equal(history.length, 1);
assert.equal(history[0].amount, 800, 'admin-recorded payment counts in history and total');
assert.equal(history[0].date, '2026-10-11', 'review date is converted to Cairo date');
assert.deepEqual(bookingBalance('member', [paid, pending], now), { hasBooking: true, total: 1, remaining: 1 });
assert.equal(bookingBalance('member', [{ ...paid, expires_on: '2026-10-01' }], now).hasBooking, false);
const agenda = trainingAgenda(member, [paid], [], [weekly], [], now);
assert.equal(agenda.length, 1, 'booked groups override unrelated academy schedule suggestions');
assert.equal(agenda[0].confirmed, true);
assert.equal(agenda[0].href, '/academy-bookings');
assert.equal(agenda[0].academyId, 'academy');
assert.equal(trainingAgenda({ ...member, academy_id: null }, [], [], [weekly], [], now).length, 0);
console.log('PASS: admin-recorded payments, paid-only totals, Cairo payment dates, booking balance and calendar agenda');
