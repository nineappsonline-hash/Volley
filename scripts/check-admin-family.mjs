import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const db=new PGlite();
await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT '00000000-0000-4000-8000-000000000099'::uuid $$;
CREATE FUNCTION public.is_super_admin() RETURNS boolean LANGUAGE sql AS $$ SELECT coalesce(current_setting('test.admin',true),'false')='true' $$;
CREATE FUNCTION public.is_account_blocked() RETURNS boolean LANGUAGE sql AS $$ SELECT false $$;
CREATE TABLE public.academies(id uuid PRIMARY KEY);
CREATE TABLE public.profiles(id uuid PRIMARY KEY, guardian_id uuid REFERENCES profiles,role text,email text,name text,gender text,birth_date date,phone text,academy_id uuid REFERENCES academies,join_date date,membership_type text,subscription_sessions integer,is_active boolean,community_visible boolean,notify_game_alerts boolean);
INSERT INTO auth.users VALUES('00000000-0000-4000-8000-000000000001'),('00000000-0000-4000-8000-000000000002');
INSERT INTO profiles(id,role,email) SELECT id,'member','test@example.com' FROM auth.users;
`);
await db.exec(readFileSync('supabase/migrations/20270102000000_super_admin_family_accounts.sql','utf8'));
const parent='00000000-0000-4000-8000-000000000001',other='00000000-0000-4000-8000-000000000002';
const details={name:'Child',gender:'male',birth_date:'2015-01-01',phone:'',academy_id:''};
const save=(p,d,id=null)=>db.query('SELECT admin_save_family_child($1,$2::jsonb,$3) id',[p,JSON.stringify(d),id]);
await assert.rejects(()=>save(parent,details),/Not authorized/);
await db.exec("SELECT set_config('test.admin','true',false)");
await db.query('SELECT admin_set_parent_account($1,true)',[parent]);
const child=(await save(parent,details)).rows[0].id;
assert.equal((await db.query('SELECT guardian_id FROM profiles WHERE id=$1',[child])).rows[0].guardian_id,parent);
assert.equal((await db.query('SELECT count(*)::int n FROM auth.users')).rows[0].n,2);
await assert.rejects(()=>save(other,details,child),/not found/);
await assert.rejects(()=>save(child,details),/login account/);
await assert.rejects(()=>save(parent,{...details,birth_date:'2999-01-01'}),/date of birth/);
await assert.rejects(()=>save(parent,{...details,name:'  '}),/name/);
await assert.rejects(()=>db.query('SELECT admin_set_parent_account($1,false)',[parent]),/still has children/);
await save(parent,{...details,name:'Updated'},child);
assert.equal((await db.query('SELECT name FROM profiles WHERE id=$1',[child])).rows[0].name,'Updated');
await db.exec("SELECT set_config('test.admin','false',false)");
await assert.rejects(()=>save(parent,details,child),/Not authorized/);
assert.equal((await db.query("SELECT has_function_privilege('anon','public.admin_save_family_child(uuid,jsonb,uuid)','EXECUTE') allowed")).rows[0].allowed,false);
await db.close();
console.log('Admin family checks passed: authorization, parent classification, child creation/editing, validation and guardian isolation.');
