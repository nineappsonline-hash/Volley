import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
process.on('uncaughtException', error => { console.error(error.message, error.where ?? '', error.position, error.internalPosition, error.internalQuery, error.query?.slice(Math.max(0,Number(error.position)-150),Number(error.position)+150), error.stack?.split('\n').slice(1,3).join('\n')); process.exit(1); });
const db=new PGlite();
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const admin=id(1),member=id(2),other=id(3),venue=id(10);
await db.exec(`
CREATE ROLE anon; CREATE ROLE authenticated;
CREATE SCHEMA auth; CREATE SCHEMA storage;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
CREATE FUNCTION public.is_super_admin() RETURNS boolean LANGUAGE sql AS $$ SELECT coalesce(current_setting('test.admin',true),'')='yes' $$;
CREATE FUNCTION public.is_account_blocked() RETURNS boolean LANGUAGE sql AS $$ SELECT false $$;
CREATE FUNCTION public.minutes_of_day(t time) RETURNS integer LANGUAGE sql IMMUTABLE AS $$ SELECT (extract(hour FROM t)*60+extract(minute FROM t))::integer $$;
CREATE TABLE public.profiles(id uuid PRIMARY KEY,role text,is_active boolean,name text);
CREATE TABLE public.academies(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),name text,slug text,description text,country text,governorate text,area text,is_public boolean,is_trial boolean);
CREATE TABLE public.sports(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),academy_id uuid,name text);
CREATE TABLE public.venues(id uuid PRIMARY KEY,name text,address text,approval_status text,court_count integer,working_hours jsonb DEFAULT '[]',unavailable_slots jsonb DEFAULT '[]');
CREATE TABLE public.venue_rentals(id uuid PRIMARY KEY,venue_id uuid,rental_date date,start_time time,hours numeric,court_number integer);
CREATE TABLE public.friendly_games(id uuid PRIMARY KEY,playground_id uuid,game_date date,start_time time,duration_hours numeric,court_number integer,status text);
CREATE TABLE storage.objects(bucket_id text,name text);
`);
await db.exec(readFileSync('supabase/migrations/20261228000000_academy_training_bookings.sql','utf8'));
for(const [uid,role] of [[admin,'super_admin'],[member,'member'],[other,'member']])await db.query('INSERT INTO profiles VALUES($1,$2,true,$2)',[uid,role]);
await db.query("INSERT INTO venues(id,name,address,approval_status,court_count) VALUES($1,'Test court','Cairo','approved',1)",[venue]);
const login=async(uid,isAdmin=false)=>db.query("SELECT set_config('test.uid',$1,false),set_config('test.admin',$2,false)",[uid,isAdmin?'yes':'no']);
const rpc=async(name,args=[],casts=[])=>{const {rows}=await db.query(`SELECT ${name}(${args.map((_,i)=>`$${i+1}${casts[i]?'::'+casts[i]:''}`).join(',')}) AS result`,args);return rows[0].result;};
await login(member);
await assert.rejects(()=>rpc('admin_create_training_academy',[JSON.stringify({name:'Test'})]),/Not authorized/);
await login(admin,true);
const aid=await rpc('admin_create_training_academy',[JSON.stringify({name:'Academy',country:'Egypt'})]);
const details={academy_id:aid,venue_id:venue,name:'Volleyball training',sport:'Volleyball',monthly_sessions:8,monthly_price:400,trial_price:50,capacity:2,schedule:Array.from({length:7},(_,weekday)=>({weekday,start:'18:00',end:'19:00'}))};
const program=await rpc('admin_save_training_program',[JSON.stringify(details)]);
await assert.rejects(()=>rpc('admin_save_training_program',[JSON.stringify({...details,monthly_price:-1})]),/check constraint/);
await assert.rejects(()=>rpc('admin_save_training_program',[JSON.stringify({...details,schedule:[{weekday:0,start:'19:00',end:'18:00'}]})]),/end must be after/);
await login(member);
const catalog=await rpc('academy_training_catalog',[aid]);
assert.equal(catalog.length,1);assert.ok(catalog[0].slots.length>=29);
const booking=await rpc('reserve_academy_training',[program,'monthly']);
let row=(await db.query('SELECT *,expires_on-registered_on days FROM academy_training_bookings WHERE id=$1',[booking])).rows[0];
assert.equal(row.days,30);assert.equal(Number(row.amount),400);assert.equal(row.details.sessions.length,8);assert.equal(row.status,'awaiting_payment');
await assert.rejects(()=>rpc('reserve_academy_training',[program,'monthly']),/overlapping/);
await db.exec('SET ROLE authenticated');
assert.equal((await db.query('SELECT * FROM academy_training_bookings')).rows.length,1);
await assert.rejects(()=>db.query("UPDATE academy_training_bookings SET status='approved'"),/permission denied/);
await db.exec('RESET ROLE');
await login(other);
await db.exec('SET ROLE authenticated');
assert.equal((await db.query('SELECT * FROM academy_training_bookings')).rows.length,0);
await db.exec('RESET ROLE');
await assert.rejects(()=>rpc('manage_academy_training_payment',[booking,'cancel']),/Not your booking/);
const slot=row.details.sessions[0];
const trial=await rpc('reserve_academy_training',[program,'trial',slot.session_date,slot.starts_at]);
const count=(await db.query('SELECT seats_left FROM training_program_slots($1) WHERE session_date=$2 AND starts_at=$3',[program,slot.session_date,slot.starts_at])).rows[0].seats_left;
assert.equal(Number(count),0);
// Direct game/rental writes cannot bypass academy occupancy checks.
await assert.rejects(()=>db.query("INSERT INTO friendly_games VALUES($1,$2,$3,$4,1,1,'open')",[id(700),venue,slot.session_date,slot.starts_at]),/reserved for an academy/);
await assert.rejects(()=>db.query("INSERT INTO venue_rentals VALUES($1,$2,$3,$4,1,1)",[id(701),venue,slot.session_date,slot.starts_at]),/reserved for an academy/);
// One shared court supports both members, but cannot be allocated to another game.
assert.equal(await rpc('pick_free_court',[venue,slot.session_date,slot.starts_at,60],['uuid','date','time','integer']),null);
await login(admin,true);
await assert.rejects(()=>rpc('admin_save_training_program',[JSON.stringify({...details,name:'Changed'}),program]),/has bookings/);
await login(member);
await assert.rejects(()=>rpc('manage_academy_training_payment',[booking,'approve']),/Only super admins/);
await assert.rejects(()=>rpc('manage_academy_training_payment',[booking,'submit','instapay',`${other}/receipt.jpg`]),/upload your receipt/);
await db.query("INSERT INTO storage.objects VALUES('game-fee-receipts',$1)",[`${member}/receipt.jpg`]);
await rpc('manage_academy_training_payment',[booking,'submit','instapay',`${member}/receipt.jpg`]);
await assert.rejects(()=>rpc('manage_academy_training_payment',[booking,'cancel']),/cannot be changed/);
await login(admin,true);
await rpc('manage_academy_training_payment',[booking,'approve']);
assert.equal((await db.query('SELECT status FROM academy_training_bookings WHERE id=$1',[booking])).rows[0].status,'approved');
await assert.rejects(()=>rpc('manage_academy_training_payment',[booking,'reject']),/Only submitted/);
// Expired unpaid holds release seats, and cannot submit a receipt.
await db.query("UPDATE academy_training_bookings SET hold_until=now()-interval '1 second' WHERE id=$1",[trial]);
await login(other);
await assert.rejects(()=>rpc('manage_academy_training_payment',[trial,'submit','e_wallet',`${other}/receipt.jpg`]),/Reservation expired/);
assert.equal(Number((await db.query('SELECT seats_left FROM training_program_slots($1) WHERE session_date=$2 AND starts_at=$3',[program,slot.session_date,slot.starts_at])).rows[0].seats_left),1);
// Free trials require no transfer and are confirmed at registration.
await login(admin,true);
const freeProgram=await rpc('admin_save_training_program',[JSON.stringify({...details,name:'Free trial',trial_price:0,schedule:details.schedule.map(s=>({...s,start:'20:00',end:'21:00'}))})]);
await login(other);
const freeSlot=(await db.query('SELECT * FROM training_program_slots($1) LIMIT 1',[freeProgram])).rows[0];
const freeBooking=await rpc('reserve_academy_training',[freeProgram,'trial',freeSlot.session_date,freeSlot.starts_at]);
assert.equal((await db.query('SELECT status FROM academy_training_bookings WHERE id=$1',[freeBooking])).rows[0].status,'approved');
await login(admin,true);
await rpc('admin_save_training_program',[JSON.stringify({active:false}),freeProgram]);
await login(other);
await assert.rejects(()=>rpc('reserve_academy_training',[freeProgram,'monthly']),/not available/);

// Public capacity reflects owner blocks, opening hours, and other court bookings.
const nextSlot=(await db.query('SELECT * FROM training_program_slots($1) ORDER BY session_date DESC LIMIT 1',[program])).rows[0];
await db.query('UPDATE venues SET blocked_dates=$1::jsonb WHERE id=$2',[JSON.stringify([{date:nextSlot.session_date.toISOString().slice(0,10),all_day:true}]),venue]);
assert.equal(Number((await db.query('SELECT seats_left FROM training_program_slots($1) WHERE session_date=$2',[program,nextSlot.session_date])).rows[0].seats_left),0);
await db.query("UPDATE venues SET blocked_dates='[]',working_hours=$1::jsonb WHERE id=$2",[JSON.stringify([{weekday:0,start:'09:00',end:'10:00'}]),venue]);
assert.ok((await db.query('SELECT * FROM training_program_slots($1)',[program])).rows.every(s=>Number(s.seats_left)===0));
await db.query("UPDATE venues SET working_hours='[]' WHERE id=$1",[venue]);

await db.close();
console.log('Academy training checks passed: admin access, 30-day terms, session capacity, court sharing, overlap prevention, RLS, receipt ownership, approvals, expiry, free trials and paused programs.');
