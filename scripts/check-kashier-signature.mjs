import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
const js=ts.transpileModule(readFileSync('src/lib/payments/kashier.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};new Function('require','module','exports',js)(createRequire(import.meta.url),module,module.exports);
const {verifyKashierSignature,amountInPiastres}=module.exports;
const key='test-key-not-a-live-credential';
const data={amount:'450.00',currency:'EGP',merchantOrderId:'order-1',status:'SUCCESS',transactionId:'TX-1',method:'card',transactionResponseCode:'00',channel:'online | e-commerce'};
data.signatureKeys=Object.keys(data).reverse();
const sign=d=>createHmac('sha256',key).update([...d.signatureKeys].sort().map(k=>`${k}=${encodeURIComponent(d[k])}`).join('&')).digest('hex');
const signature=sign(data);
assert.equal(verifyKashierSignature(data,signature,key),true);
assert.equal(verifyKashierSignature(data,signature.toUpperCase(),key),true);
for(const field of ['amount','currency','merchantOrderId','status','transactionId','method'])assert.equal(verifyKashierSignature({...data,[field]:'tampered'},signature,key),false);
assert.equal(verifyKashierSignature(data,null,key),false);
assert.equal(verifyKashierSignature(data,'0',key),false);
const missing={...data,signatureKeys:['amount']};assert.equal(verifyKashierSignature(missing,sign(missing),key),false);
assert.equal(verifyKashierSignature({...data,signatureKeys:[...data.signatureKeys,'amount']},signature,key),false);
assert.equal(amountInPiastres('450.00'),45000);assert.equal(amountInPiastres(450),45000);
for(const v of ['NaN','Infinity',-1,'0','1.001','1e2','',null])assert.equal(amountInPiastres(v),null);
console.log('Kashier signature checks passed: HMAC, tampering, missing fields, invalid signatures, exact monetary values.');
